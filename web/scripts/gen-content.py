#!/usr/bin/env python3
"""Generate typed content modules in src/content/ from the original Py Dojo sources.
Run from web/: python3 scripts/gen-content.py
Sources: tools/content-src/ (depth.json, glossary.json, bank.ts, code.js, spot.js)
and /tmp/olddata.json (a dump of the old app's BELTS, BELT_ERR, ERRS, ERR_PY, ERR_HIER).
"""
import json, re, subprocess, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "tools" / "content-src"
OUT = ROOT / "src" / "content"
old = json.load(open("/tmp/olddata.json"))
HDR = "/* AUTO-GENERATED by scripts/gen-content.py from the original Py Dojo sources. Do not edit by hand. */\n"
def w(name, body): (OUT / name).write_text(HDR + body + "\n")
J = lambda o: json.dumps(o, ensure_ascii=False, indent=1)

# curriculum
w("curriculum.ts", 'import type { Belt } from "../types";\nexport const BELTS: Belt[] = ' + J(old["BELTS"]) +
  ";\nexport const BELT_ERR: Record<string, string> = " + J(old["BELT_ERR"]) + ";\n")
# depth
w("depth.ts", 'import type { Depth } from "../types";\nexport const DEPTH: Record<string, Depth> = ' + J(json.load(open(SRC / "depth.json"))) + ";\n")
# glossary
g = json.load(open(SRC / "glossary.json")); assert len(g) == 204
w("glossary.ts", 'import type { GlossEntry } from "../types";\nexport const GLOSSARY: GlossEntry[] = ' + J(g) + ";\n")

# errors: 34 lesson errors from the old app + 9 errors learners meet on later belts (messages captured from real runs)
errs = [dict(e, belt="White") for e in old["ERRS"]]
EXTRA = [
 ("Dicts", "Orange", "KeyError", 'zones = {"Colombo": 15}\nprint(zones["Kandy"])', "The dict has no key with that name.", 'Check with "Kandy" in zones, or use zones.get("Kandy").'),
 ("Modules & imports", "Green", "ModuleNotFoundError", "import geopandaz", "Python can't find a module with that name: a typo, or it isn't installed.", "Fix the spelling or install it with pip."),
 ("Files", "Blue", "FileNotFoundError", 'open("districts.csv")', "There is no file with that name in the folder Python is running from.", "Check the file name and the current folder (pathlib helps)."),
 ("Recursion", "Green", "RecursionError", "def walk(n):\n    return walk(n + 1)\nwalk(0)", "The function calls itself forever, with no base case to stop it.", "Add a base case that returns without calling itself."),
 ("Scope", "Green", "UnboundLocalError", "count = 0\ndef add():\n    count = count + 1\nadd()", "Assigning to a name inside a function makes it local, so it has no value yet when read.", "Pass the value in and return the result (or use global sparingly)."),
 ("Iterators", "Brown", "StopIteration", "it = iter([1])\nnext(it)\nnext(it)", "The iterator has no more items to give.", "Use a for loop, or next(it, default)."),
 ("Testing", "Red", "AssertionError", "area = 12\nassert area == 15, \"area should be 15\"", "An assert found that something you expected to be true is false.", "Fix the code under test, or the expectation if it was wrong."),
 ("Lists", "Orange", "IndexError", 'cities = ["Galle", "Kandy"]\nprint(cities[2])', "Lists start at index 0, so a 2-item list has indexes 0 and 1 only.", "Use an index below len(cities), or cities[-1] for the last item."),
 ("Exceptions", "Blue", "ImportError", "from math import squareroot", "The module exists but has no name like that inside it.", "Check the spelling: from math import sqrt."),
]
def run(code):
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True)
    lines = [l for l in r.stderr.strip().split("\n") if l]
    return lines[-1] if lines else ""
for topic, belt, err, code, why, fix in EXTRA:
    msg = run(code); assert msg.startswith(err), (err, msg)
    errs.append({"topic": topic, "error": err, "code": code, "why": why, "fix": fix, "message": msg, "traceback": "", "belt": belt})
assert len(errs) == 43, len(errs)
w("errors.ts", 'import type { ErrEntry } from "../types";\nexport const ERR_PY = ' + J(old["ERR_PY"]) + ";\nexport const ERRORS: ErrEntry[] = " + J(errs) +
  ";\nexport const ERR_HIER: string[][] = " + J(old["ERR_HIER"]) + ";\n")

# exercise bank, coding templates and spot-the-error templates: port the source modules with types
bank = (SRC / "bank.ts").read_text()
bank = re.sub(r"^type R = .*\ntype Ex = .*\ntype Tpl = .*\ntype Lesson = .*\n", 'import type { BankLesson, R } from "../types";\n', bank, flags=re.M)
bank = bank.replace("const BANK: Record<string, Lesson>", "export const BANK: Record<string, BankLesson>").replace("const CITIES", "export const BANK_CITIES").replace("r.pick(CITIES)", "r.pick(BANK_CITIES)")
bank = re.sub(r'BANK\["([^"]+)"\]\.ex\.push', lambda m: f'need("{m.group(1)}").ex.push', bank)
bank = bank.replace("const COORDS:", 'const need = (k: string): BankLesson => { const l = BANK[k]; if (!l) throw new Error(k); return l; };\nconst COORDS:')
bank = re.sub(r"COORDS\[c\](\[\d\])", r"(COORDS[c] ?? [0, 0])\1", bank)
bank = re.sub(r"p = COORDS\[c\];", "p = COORDS[c] ?? [0, 0];", bank)
def unused(line, pat, rep):
    i = line.find(pat)
    return line.replace(pat, rep, 1) if i >= 0 and not re.search(r"\br\.(pick|int)\(", line[i + len(pat):]) else line
bank = "\n".join(unused(l, "make: (r: R) =>", "make: (_r: R) =>") for l in bank.split("\n"))
(OUT / "bank.ts").write_text(HDR + bank)
code = (SRC / "code.js").read_text()
code = code.replace("const PG_CITIES =", 'import type { CodeTpl } from "../types";\nconst PG_CITIES: Record<string, [number, number]> =').replace("const CODE_TPL = [", "export const CODE_TPL: CodeTpl[] = [")
code = code.replace("p = PG_CITIES[c];", "p = PG_CITIES[c] ?? [0, 0];")
(OUT / "code.ts").write_text(HDR + code)
spot = (SRC / "spot.js").read_text()
spot = spot.replace("const SPOT_CITIES", 'import type { SpotTpl } from "../types";\nconst SPOT_CITIES').replace("const SPOT_TPL = [", "export const SPOT_TPL: SpotTpl[] = [").replace("const SPOT_POOL", "export const SPOT_POOL")
spot = "\n".join(unused(l, "make: r =>", "make: _r =>") for l in spot.split("\n"))
spot = re.sub(r'(id:"geoLat".*?)const c = r\.pick\(SPOT_CITIES\); ', r'\1r.pick(SPOT_CITIES); ', spot)
(OUT / "spot.ts").write_text(HDR + spot)
print("ok", len(errs), "errors,", len(g), "terms")
